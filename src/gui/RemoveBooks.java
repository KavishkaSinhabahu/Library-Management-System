    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        String bookID = jTextField1.getText();

        if (bookID.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter Book ID", "Warning", JOptionPane.ERROR_MESSAGE);
        } else {

            try {
                ResultSet rs = MySQL.search("SELECT * FROM `books` WHERE `book_id`='" + bookID + "'");
                if (rs.next()) {
                    ResultSet rs1 = MySQL.search("SELECT * FROM `book_category` WHERE `cat_id`='" + rs.getString("category_id") + "'");
                    rs1.next();
                    String category = rs1.getString("category_name");

                    jTextField4.setText(rs.getString("book_name"));
                    jTextField5.setText(rs.getString("publisher"));
                    jComboBox3.setSelectedItem(category);

                    JOptionPane.showMessageDialog(this, "Book Found", "Success", JOptionPane.INFORMATION_MESSAGE);

                } else {
                    JOptionPane.showMessageDialog(this, "Invalid Book ID", "Warning", JOptionPane.ERROR_MESSAGE);;
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }

    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

        String bookID = jTextField1.getText();
        String reason = jComboBox4.getSelectedItem().toString();

        try {
            ResultSet rs = MySQL.search("SELECT * FROM `books` WHERE `book_id`='" + bookID + "'");
            rs.next();
            ResultSet rs1 = MySQL.search("SELECT * FROM `bookremove_reason` WHERE `reason`='" + reason + "'");
            rs1.next();
            String rea = rs1.getString("r_id");

            MySQL.iud("UPDATE `books` SET `status` ='2' WHERE `book_id`='" + bookID + "'");
            MySQL.iud("INSERT INTO `removebooks`(`reason_id`,`book_id`) VALUES('" + rea + "','" + rs.getString("b_id") + "')");

            JOptionPane.showMessageDialog(this, "Book Removed", "Success", JOptionPane.INFORMATION_MESSAGE);

            ResultSet rs2 = MySQL.search("SELECT * FROM `book_stock` WHERE `bookname`='" + rs.getString("book_name") + "'");
            if (rs2.next()) {
                int oldQty = Integer.parseInt(rs2.getString("qty"));
                int finalQty = oldQty - Integer.parseInt("1");
                String qtyBook = String.valueOf(finalQty);
                MySQL.iud("UPDATE `book_stock` SET `qty`='" + qtyBook + "' WHERE `bookname`='" + rs.getString("book_name") + "'");
                JOptionPane.showMessageDialog(this, "Quantity Updated", "Success", JOptionPane.INFORMATION_MESSAGE);
                resetField();
            }
            resetField();
        } catch (Exception e) {
            e.printStackTrace();
        }

    }//GEN-LAST:event_jButton3ActionPerformed

