    public void loadUsers(String text) {
        try {
            ResultSet rs = MySQL.search("SELECT * FROM `due_payments` INNER JOIN `books` ON `due_payments`.book_id =`books`.b_id INNER JOIN `student` ON `student`.ac_id = `due_payments`.student_id WHERE `student`.`uniquiID` LIKE '" + text + "%' OR `books`.`book_id` LIKE '" + text + "%' ");
            DefaultTableModel dtm = (DefaultTableModel) jTable2.getModel();
            dtm.setRowCount(0);
            theader();
            while (rs.next()) {
                Vector v = new Vector();

                v.add(rs.getString("books.book_id"));
                v.add(rs.getString("student.uniquiID"));
                v.add(rs.getString("due_payments.charge_per_day"));
                v.add(rs.getString("due_payments.due_dates"));
                String date = rs.getString("due_payments.payment_date");
                Date date1 = new SimpleDateFormat("yyyy-MM-dd").parse(date);

                String strDate = sdf.format(date1);

                v.add(strDate);
                dtm.addRow(v);

            }
        } catch (Exception e) {
            e.printStackTrace();
        }

    }

