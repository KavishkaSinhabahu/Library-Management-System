    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        JFileChooser backupPathFileChooserChooser = new JFileChooser();
        int retrnVal = backupPathFileChooserChooser.showOpenDialog(this);

        if (retrnVal == JFileChooser.APPROVE_OPTION) {
            String selectFileName = backupPathFileChooserChooser.getSelectedFile().getName();
            String selectFilePath = backupPathFileChooserChooser.getCurrentDirectory().getPath();
            String backupPath = selectFilePath + "\\" + selectFileName;
            jTextField1.setText(backupPath);

        }

    }//GEN-LAST:event_jButton2ActionPerformed

