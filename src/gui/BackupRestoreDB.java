    private void jLabel7MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jLabel7MouseClicked

        String name = jTextField3.getText();
        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Empty Fields", "Warning", JOptionPane.ERROR_MESSAGE);
        } else {
            try {
                ResultSet rs = MySQL.search("SELECT * FROM `city` WHERE `city_name`='" + name + "'");
                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "city Name Already Here", "Warning", JOptionPane.ERROR_MESSAGE);
                } else {
                    MySQL.iud("INSERT INTO `city`(`city_name`) VALUES('" + name + "')");
                    JOptionPane.showMessageDialog(this, "Saved", "Success", JOptionPane.INFORMATION_MESSAGE);
                    jTextField3.setText("");
                }

            } catch (Exception e) {
                e.printStackTrace();
            }
        }

    }//GEN-LAST:event_jLabel7MouseClicked

